def predict_price(company, car_age, kms_driven, fuel_type, model=best_pipeline):
    sample = pd.DataFrame([{
        'company': company,
        'car_age': car_age,
        'kms_driven': kms_driven,
        'fuel_type': fuel_type
    }])
    return model.predict(sample)[0]

