print("Rows before cleaning:", len(df))

# Keep only rows where 'year' is a clean 4-digit number
df = df[df['year'].astype(str).str.match(r'^\d{4}$')].copy()

# Drop rows where price wasn't listed
df = df[df['Price'] != 'Ask For Price']

# Clean Price: remove commas, convert to int
df['Price'] = df['Price'].astype(str).str.replace(',', '', regex=False).astype(int)

# Convert year to int
df['year'] = df['year'].astype(int)

# Clean kms_driven: remove commas + ' kms' suffix, drop missing/non-numeric
df = df[df['kms_driven'].notna()]
df['kms_driven'] = (df['kms_driven'].astype(str)
                     .str.replace(',', '', regex=False)
                     .str.replace(' kms', '', regex=False))
df = df[df['kms_driven'].str.match(r'^\d+$')]
df['kms_driven'] = df['kms_driven'].astype(int)

# Drop rows with missing fuel type
df = df[df['fuel_type'].notna()]

# Remove the extreme outlier price (clear data-entry error)
df = df[df['Price'] < 6_000_000]

df = df.reset_index(drop=True)
print("Rows after cleaning:", len(df))
